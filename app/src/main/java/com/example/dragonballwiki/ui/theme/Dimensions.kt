package com.example.dragonballwiki.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Image size constants used throughout the app.
 * Provides consistent sizing for character images and loading indicators.
 */
object ImageSizes {
    /**
     * Thumbnail size for character images in list view (100dp).
     */
    val characterListThumbnail = 100.dp

    /**
     * Hero image size for character detail view (300dp).
     */
    val characterDetailHero = 300.dp

    /**
     * Thumbnail size for transformation images (100dp).
     */
    val transformationThumbnail = 100.dp

    /**
     * Size for circular loading indicator (150dp).
     */
    val loadingIndicator = 150.dp

    /**
     * Size for Dragon Ball loading image (280dp).
     */
    val loadingDragonBall = 280.dp
}

